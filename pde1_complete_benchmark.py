def make_features(hist: np.ndarray, valid: np.ndarray, hist_dt: Sequence[float],
                  next_dt: float, geom: Dict[str, Any]) -> np.ndarray:
    """Feature layout: 2H vector channels + H validity + H time gaps + 1 next-dt + 5 gauge-invariant scalar maps."""
    hist = np.asarray(hist, dtype=np.float32)
    h, two, H, W = hist.shape
    if two != 2 or valid.shape != (h, H, W) or len(hist_dt) != h:
        raise ValueError("History/validity/time feature shapes do not agree.")
    hist_maps = np.broadcast_to(np.asarray(hist_dt, np.float32)[:, None, None], (h, H, W))
    next_map = np.full((1, H, W), float(next_dt), dtype=np.float32)
    # Geometry is supplied to *all* learned baselines, not only ETD models.
    # Crucially, the local spin-connection one-form is NOT supplied as an
    # ordinary scalar channel: it is gauge-dependent and belongs in the
    # parallel-transport/connection-Laplacian operator. Treating it as a
    # pointwise scalar would break local-frame covariance of the learned fibre
    # reaction. The five static channels are gauge-invariant chart coordinates,
    # the metric factor, Gaussian curvature, and the discrete spin label.
    # (The spin label is constant over the chart and invariant under frame
    # rotations; it distinguishes spin-1 vector and spin-2 tensor fibres.)
    xcoord = geom["X"] / max(float(geom["x_extent"]), 1e-12)
    ycoord = geom["Y"] / max(float(geom["y_extent"]), 1e-12)
    f = np.asarray(geom["metric_factor"], dtype=np.float64)[:, None]
    metric = np.broadcast_to(f, (H, W))
    curvature = np.full((H, W), float(geom["curvature"]), dtype=np.float64)
    spin_label = np.full((H, W), float(geom["spin"]), dtype=np.float64)
    coords = np.stack([xcoord, ycoord, metric, curvature, spin_label], axis=0).astype(np.float32)
    return np.concatenate([hist.reshape(2 * h, H, W),
                           np.asarray(valid, np.float32), hist_maps,
                           next_map, coords], axis=0).astype(np.float32)


class TrajectoryWindows(Dataset):
    def __init__(self, trajectories: np.ndarray, hist: int, scale: float,
                 stop_step: int, geom: Dict[str, Any], dt: float):
        if scale <= 0 or not np.isfinite(scale):
            raise ValueError("Training normalization scale must be finite and positive.")
        if stop_step >= trajectories.shape[1] - 1:
            raise ValueError("stop_step must leave a one-step target after the training prefix.")
        self.items = []
        self.trajectory_indices: List[List[int]] = [[] for _ in range(len(trajectories))]
        H, W = geom["mask"].shape
        validity = np.ones((hist, H, W), dtype=np.float32)
        for tid in range(len(trajectories)):
            for i in range(hist - 1, stop_step):
                s = i - hist + 1
                hstate = trajectories[tid, s:i + 1] / scale
                feat = make_features(hstate, validity, [1.0] * hist, 1.0, geom)
                idx = len(self.items)
                self.items.append((feat, hstate[-1].copy(),
                                   trajectories[tid, i + 1] / scale, float(dt)))
                self.trajectory_indices[tid].append(idx)

    def __len__(self):
        return len(self.items)

    def __getitem__(self, index):
        x, last, target, dt = self.items[index]
        return (torch.from_numpy(x), torch.from_numpy(last.astype(np.float32)),
                torch.from_numpy(target.astype(np.float32)), torch.tensor(dt, dtype=torch.float32))



class TrajectoryBalancedBatchSampler(Sampler):
    """Use one window from each independent trajectory per sampling cycle.

    Every item is visited exactly once per epoch. Each cycle has balanced
    trajectory coverage, avoiding batches dominated by overlapping windows
    from a small number of trajectories. This changes neither examples nor
    optimizer updates when batch_size equals the number of trajectories.
    """
    def __init__(self, trajectory_indices: Sequence[Sequence[int]], batch_size: int,
                 seed: int):
        self.groups = [list(map(int, g)) for g in trajectory_indices]
        if len(self.groups) < 2 or any(len(g) == 0 for g in self.groups):
            raise ValueError("Trajectory-balanced sampling requires >=2 nonempty trajectories.")
        lengths = {len(g) for g in self.groups}
        if len(lengths) != 1:
            raise ValueError("Trajectory-balanced sampling requires equal windows per trajectory.")
        if int(batch_size) < 1:
            raise ValueError("batch_size must be positive.")
        self.batch_size = int(batch_size)
        self.seed = int(seed)
        self.epoch = 0
        self.windows_per_trajectory = len(self.groups[0])
        self.n_batches = self.windows_per_trajectory * math.ceil(len(self.groups) / self.batch_size)

    def __iter__(self):
        g = torch.Generator()
        g.manual_seed(self.seed + self.epoch * 1000003)
        self.epoch += 1
        orders = [torch.randperm(len(group), generator=g).tolist() for group in self.groups]
        for step in range(self.windows_per_trajectory):
            cycle = [group[orders[t][step]] for t, group in enumerate(self.groups)]
            perm = torch.randperm(len(cycle), generator=g).tolist()
            cycle = [cycle[i] for i in perm]
            for start in range(0, len(cycle), self.batch_size):
                yield cycle[start:start + self.batch_size]

    def __len__(self):
        return self.n_batches

def estimate_train_scale(train: np.ndarray, train_steps: int, geom: Dict[str, Any]) -> float:
    """Area-weighted RMS estimated only on training trajectories/prefix."""
    area = geom["area_grid"].astype(np.float64)
    area = area / area.sum()
    z = train[:, :train_steps + 1].astype(np.float64)
    mean_square = np.mean(np.sum(z * z * area[None, None, None], axis=(-2, -1)) / 2.0)
    scale = float(math.sqrt(max(mean_square, 1e-24)))
    if not np.isfinite(scale) or scale <= 0:
        raise ValueError("Invalid training-only RMS scale.")
    return scale


def estimate_residual_bound(train: np.ndarray, train_steps: int, scale: float,
                            dt: float, multiplier: float, quantile: float = 0.995) -> float:
    """Train-only forcing bound from normalized observed increments per unit time."""
    if not (0.0 < quantile < 1.0) or multiplier <= 0:
        raise ValueError("Invalid residual-bound settings.")
    diffs = (train[:, 1:train_steps + 1] - train[:, :train_steps]) / (scale * dt)
    mag = np.sqrt(np.sum(diffs.astype(np.float64) ** 2, axis=2))
    q = float(np.quantile(mag, quantile))
    bound = max(0.02, multiplier * q)
    if not np.isfinite(bound):
        raise FloatingPointError("Training-only residual bound is non-finite.")
    return bound


