def reference_refinement(case: Case, geom: Dict[str, Any], args,
                         audit_label: str = "test") -> dict:
    """Full-horizon Strang refinement on independent initial conditions.

    The coarse and fine references share initial data but use doubled splitting
    and reaction substeps. Every experiment case receives a full-horizon audit;
    parameter-sensitivity cases are not exempted.
    """
    per_trajectory = []
    n_audit = max(2, int(args.reference_audit_trajectories))
    full_steps = int(args.reference_audit_steps)
    for tid in range(n_audit):
        state0 = make_initial(88001 + 7919 * tid, geom, case.pde)
        coarse = state0.copy(); fine = state0.copy()
        one_coarse = integrate_saved_interval(state0, geom, case, args.dt,
                                              args.reference_substeps,
                                              args.reaction_substeps)
        one_fine = integrate_saved_interval(state0, geom, case, args.dt,
                                            2 * args.reference_substeps,
                                            2 * args.reaction_substeps)
        one_err = metric_relative_l2(one_coarse, one_fine, geom["area_grid"])
        for _ in range(full_steps):
            coarse = integrate_saved_interval(coarse, geom, case, args.dt,
                                              args.reference_substeps, args.reaction_substeps)
            fine = integrate_saved_interval(fine, geom, case, args.dt,
                                            2 * args.reference_substeps,
                                            2 * args.reaction_substeps)
            if not np.isfinite(coarse).all() or not np.isfinite(fine).all():
                raise FloatingPointError(f"Reference refinement non-finite for {case.name}, audit trajectory={tid}.")
        full_err = metric_relative_l2(coarse, fine, geom["area_grid"])
        per_trajectory.append(dict(trajectory=tid, one_step_relative_difference=one_err,
                                   full_horizon_relative_difference=full_err,
                                   coarse_max_abs=float(np.max(np.abs(coarse))),
                                   fine_max_abs=float(np.max(np.abs(fine)))))
    vals = np.asarray([r["full_horizon_relative_difference"] for r in per_trajectory])
    ones = np.asarray([r["one_step_relative_difference"] for r in per_trajectory])
    # Save the individual audit trajectories next to the scalar summary.
    audit_path = args.out / case.name / f"reference_refinement_{audit_label}_by_trajectory.csv"
    _atomic_csv(pd.DataFrame(per_trajectory), audit_path)
    return dict(case=case.name, audit_geometry=audit_label,
                curvature=float(geom["curvature"]),
                grid_height=int(geom["height"]), grid_width=int(geom["width"]),
                n_audit_trajectories=n_audit,
                reference_audit_steps=full_steps,
                one_step_mean=float(ones.mean()), one_step_max=float(ones.max()),
                full_horizon_mean=float(vals.mean()), full_horizon_std=float(vals.std(ddof=1)),
                full_horizon_max=float(vals.max()),
                coarse_split_substeps=args.reference_substeps,
                fine_split_substeps=2 * args.reference_substeps,
                coarse_reaction_substeps=args.reaction_substeps,
                fine_reaction_substeps=2 * args.reaction_substeps)


def _plaquette_holonomy(curvature: float, spin: int, x0: float = 0.0,
                         y0: float = -0.1, dx: float = 0.08, dy: float = 0.07) -> float:
    _, fp, _ = _metric_factor(np.array([y0, y0 + dy]), curvature)
    # Parallel transport around an oriented rectangle: x at y0, up, reverse x
    # at y0+dy, down. Sign convention yields +spin*K times enclosed area.
    angle = spin * (fp[0] - fp[1]) * dx
    f, _, _ = _metric_factor(np.array([y0, y0 + dy]), curvature)
    area = 0.5 * (f[0] + f[1]) * dx * dy
    return angle / area


def _relative_matrix_error(a: np.ndarray, b: np.ndarray) -> float:
    return float(np.linalg.norm(a - b) / max(np.linalg.norm(b), 1e-14))


def self_test() -> dict:
    checks: Dict[str, Any] = {}
    # Balanced sampling: one window per trajectory per batch, exact once/epoch.
    toy_groups = [[t * 5 + j for j in range(5)] for t in range(4)]
    toy_sampler = TrajectoryBalancedBatchSampler(toy_groups, batch_size=4, seed=7721)
    toy_batches = list(iter(toy_sampler))
    toy_flat = [idx for batch in toy_batches for idx in batch]
    assert len(toy_batches) == 5 and all(len(batch) == 4 for batch in toy_batches)
    assert len(toy_flat) == len(set(toy_flat)) == 20
    assert set(toy_flat) == set(range(20))
    assert all(len({idx // 5 for idx in batch}) == 4 for batch in toy_batches)
    checks["trajectory_balanced_sampler_exact_coverage"] = {
        "batches": len(toy_batches), "examples": len(toy_flat),
        "one_per_trajectory_per_batch": True}

    # Analytic curvature, graph symmetry/PSD and holonomy for K<0,0,K>0.
    for K in (-0.8, 0.0, 0.8):
        g = build_geometry(7, 9, K, spin=1, with_connection=True)
        L = g["laplacian"].toarray()
        ev = np.linalg.eigvalsh(L)
        assert np.max(np.abs(L - L.T)) < 1e-10
        assert ev.min() > -1e-8
        observed = _plaquette_holonomy(K, 1)
        if K == 0:
            assert abs(observed) < 1e-10
        else:
            assert abs(observed - K) / abs(K) < 0.04, (K, observed)
        checks[f"geometry_K_{K}"] = dict(min_graph_eigenvalue=float(ev.min()),
                                         orthogonality=g["orthogonality"],
                                         holonomy_per_area=observed)
    # Curvature normalization: same x-scale at y=0 for all K.
    for K in (-0.8, 0.0, 0.8):
        f, _, _ = _metric_factor(np.array([0.0]), K)
        assert abs(float(f[0]) - 1.0) < 1e-12
    checks["metric_scale_normalization"] = "PASS"

    # At K=0, connection and scalar graph operators must coincide exactly.
    g0c = build_geometry(7, 9, 0.0, spin=1, with_connection=True)
    g0s = build_geometry(7, 9, 0.0, spin=1, with_connection=False)
    k0err = _relative_matrix_error(g0c["laplacian"].toarray(), g0s["laplacian"].toarray())
    assert k0err < 1e-12
    # At K != 0, connection operator must differ from the scalar componentwise one.
    gp = build_geometry(7, 9, 0.8, spin=1, with_connection=True)
    gps = build_geometry(7, 9, 0.8, spin=1, with_connection=False)
    diff = _relative_matrix_error(gp["laplacian"].toarray(), gps["laplacian"].toarray())
    assert diff > 1e-4
    checks["connection_vs_scalar_operator"] = dict(K0_relative_error=k0err, Kpos_relative_difference=diff)

    # Heat contractivity and ETD/reference agreement for both spin representations.
    rng = np.random.default_rng(11)
    for spin in (1, 2):
        g = build_geometry(7, 9, 0.8, spin, with_connection=True)
        z = rng.normal(size=(2, 7, 9)) * 0.1
        h = heat_numpy(z, 0.12, g, 0.03)
        area = g["area_grid"]
        before = float(np.sum(area[None] * z * z))
        after = float(np.sum(area[None] * h * h))
        assert after <= before + 1e-10
        # Torch ETD zero-residual must match the independent NumPy heat action.
        gt = {k: torch.as_tensor(g[k]) for k in ("V", "eig", "mass_sqrt", "wet_idx")}
        xt = torch.from_numpy(z[None].astype(np.float32))
        rt = torch.zeros_like(xt)
        dt = torch.tensor([[[[0.12]]]], dtype=torch.float32)
        yt = heat_etd(xt, rt, dt, gt, 0.03)[0].numpy()
        err = _relative_matrix_error(yt, h.astype(np.float32))
        assert err < 2e-5, (spin, err)
        checks[f"spin{spin}_heat_contractivity"] = after / before
        checks[f"spin{spin}_torch_numpy_heat_error"] = err

    # Local fibre map must be equivariant for spin 1 and spin 2 representations.
    for spin in (1, 2):
        set_seed(100 + spin)
        model = EquivariantFibreResidual(hist=3, width=12).eval()
        nn.init.normal_(model.net[-1].weight, std=0.08)
        nn.init.normal_(model.net[-1].bias, std=0.02)
        x = torch.randn(2, 18, 7, 9)
        x[:, 6:9] = torch.rand_like(x[:, 6:9])
        x[:, 9:12] = torch.ones_like(x[:, 9:12])
        y = model(x)
        theta = 0.61
        angle = spin * theta
        R = torch.tensor([[math.cos(angle), -math.sin(angle)],
                          [math.sin(angle), math.cos(angle)]], dtype=x.dtype)
        xr = x.clone()
        vel = x[:, :6].reshape(2, 3, 2, 7, 9)
        rotated = torch.empty_like(vel)
        rotated[:, :, 0] = R[0, 0] * vel[:, :, 0] + R[0, 1] * vel[:, :, 1]
        rotated[:, :, 1] = R[1, 0] * vel[:, :, 0] + R[1, 1] * vel[:, :, 1]
        xr[:, :6] = rotated.reshape(2, 6, 7, 9)
        yr = model(xr)
        expected = torch.empty_like(y)
        expected[:, 0] = R[0, 0] * y[:, 0] + R[0, 1] * y[:, 1]
        expected[:, 1] = R[1, 0] * y[:, 0] + R[1, 1] * y[:, 1]
        e = float((torch.linalg.norm(yr - expected) / torch.linalg.norm(expected).clamp_min(1e-12)).detach())
        assert e < 2e-6, (spin, e)
        checks[f"spin{spin}_fibre_equivariance"] = e
        # O(2) also includes reflections, not only SO(2) rotations.
        J = torch.tensor([[1.0, 0.0], [0.0, -1.0]], dtype=x.dtype)
        xj = x.clone()
        vj = x[:, :6].reshape(2, 3, 2, 7, 9)
        xjr = torch.empty_like(vj)
        xjr[:, :, 0] = J[0, 0] * vj[:, :, 0] + J[0, 1] * vj[:, :, 1]
        xjr[:, :, 1] = J[1, 0] * vj[:, :, 0] + J[1, 1] * vj[:, :, 1]
        xj[:, :6] = xjr.reshape(2, 6, 7, 9)
        yj = model(xj)
        yj_expected = torch.stack([y[:, 0], -y[:, 1]], dim=1)
        ej = float((torch.linalg.norm(yj - yj_expected) /
                    torch.linalg.norm(yj_expected).clamp_min(1e-12)).detach())
        assert ej < 2e-6, (spin, ej)
        checks[f"spin{spin}_fibre_reflection_equivariance"] = ej

        # A pointwise fibre reaction must be equivariant under an independent
        # frame rotation at EVERY base point, not merely one global rotation.
        # This is the key test that would fail if the gauge potential A_mu were
        # fed to the reaction network as an ordinary scalar image channel.
        rng_local = np.random.default_rng(700 + spin)
        theta_field = torch.from_numpy(rng_local.uniform(-2.5, 2.5, size=(2, 7, 9)).astype(np.float32))
        angle_field = spin * theta_field
        cc = torch.cos(angle_field)[:, None]
        ss = torch.sin(angle_field)[:, None]
        vel0 = x[:, :6].reshape(2, 3, 2, 7, 9)
        vel_local = torch.empty_like(vel0)
        cfield = cc[:, None]
        sfield = ss[:, None]
        vel_local[:, :, 0] = cfield[:, 0] * vel0[:, :, 0] - sfield[:, 0] * vel0[:, :, 1]
        vel_local[:, :, 1] = sfield[:, 0] * vel0[:, :, 0] + cfield[:, 0] * vel0[:, :, 1]
        x_local = x.clone()
        x_local[:, :6] = vel_local.reshape(2, 6, 7, 9)
        y_local = model(x_local)
        expected_local = torch.empty_like(y)
        expected_local[:, 0] = cc[:, 0] * y[:, 0] - ss[:, 0] * y[:, 1]
        expected_local[:, 1] = ss[:, 0] * y[:, 0] + cc[:, 0] * y[:, 1]
        local_err = float((torch.linalg.norm(y_local - expected_local) /
                           torch.linalg.norm(expected_local).clamp_min(1e-12)).detach())
        assert local_err < 3e-6, (spin, local_err)
        checks[f"spin{spin}_pointwise_local_gauge_reaction_equivariance"] = local_err

    # Geometry feature maps expose only gauge-invariant scalars to every
    # learned baseline. The final channel is the spin representation label;
    # curvature is the preceding channel. No connection one-form appears.
    geom_flat = build_geometry(7, 9, 0.0, 1, True)
    geom_pos = build_geometry(7, 9, 0.8, 1, True)
    dummy_hist = np.zeros((3, 2, 7, 9), dtype=np.float32)
    dummy_valid = np.ones((3, 7, 9), dtype=np.float32)
    feat_flat = make_features(dummy_hist, dummy_valid, [1, 1, 1], 1, geom_flat)
    feat_pos = make_features(dummy_hist, dummy_valid, [1, 1, 1], 1, geom_pos)
    assert feat_flat.shape == feat_pos.shape == (18, 7, 9)
    assert np.allclose(feat_flat[-1], 1.0) and np.allclose(feat_pos[-1], 1.0)
    assert not np.allclose(feat_flat[-2], feat_pos[-2])
    geom_spin2 = build_geometry(7, 9, 0.8, 2, True)
    feat_spin2 = make_features(dummy_hist, dummy_valid, [1, 1, 1], 1, geom_spin2)
    assert np.allclose(feat_spin2[-1], 2.0)
    checks["gauge_invariant_geometry_features_for_all_baselines"] = "PASS"

    # The generic FNO residual is a flexible, unconstrained baseline, not a
    # gauge-equivariant architecture. Verify and record that distinction so it
    # cannot accidentally be described as covariant in downstream reporting.
    set_seed(4401)
    generic_fno = ConnectionETDModel(in_c=18, width=8, modes=2).eval()
    xg = torch.randn(1, 18, 7, 9)
    with torch.no_grad():
        yg = generic_fno.net(xg)
        theta = torch.from_numpy(np.random.default_rng(4402).uniform(
            -1.7, 1.7, size=(1, 7, 9)).astype(np.float32))[:, None]
        cg, sg = torch.cos(theta), torch.sin(theta)
        vg = xg[:, :6].reshape(1, 3, 2, 7, 9)
        vgr = torch.stack([cg * vg[:, :, 0] - sg * vg[:, :, 1],
                           sg * vg[:, :, 0] + cg * vg[:, :, 1]], dim=2)
        xgr = xg.clone()
        xgr[:, :6] = vgr.reshape(1, 6, 7, 9)
        ygr = generic_fno.net(xgr)
        y_expected = torch.stack([cg[:, 0] * yg[:, 0] - sg[:, 0] * yg[:, 1],
                                  sg[:, 0] * yg[:, 0] + cg[:, 0] * yg[:, 1]], dim=1)
        generic_fno_defect = float((torch.linalg.norm(ygr - y_expected) /
                                    torch.linalg.norm(y_expected).clamp_min(1e-12)).detach())
    assert generic_fno_defect > 1e-3, generic_fno_defect
    checks["generic_fno_residual_gauge_status"] = {
        "status": "NOT_EQUIVARIANT_BY_DESIGN",
        "measured_local_gauge_defect": generic_fno_defect}

    # Discrete local gauge covariance: changing each vertex's frame by G_i
    # must transform the assembled operator as L' = G L G^T.
    for spin in (1, 2):
        g = build_geometry(6, 8, 0.8, spin, True)
        rng_g = np.random.default_rng(100 + spin)
        theta = rng_g.uniform(-0.7, 0.7, size=6 * 8)
        rotations = []
        for a in spin * theta:
            c, ss = math.cos(a), math.sin(a)
            rotations.append(np.array([[c, -ss], [ss, c]], dtype=np.float64))
        G = sp.block_diag(rotations, format="csr")
        L = g["laplacian"].toarray()
        transformed = sp.lil_matrix(L.shape, dtype=np.float64)
        I2 = np.eye(2)
        for i, j, P, weight in g["edge_records"]:
            Gi, Gj = rotations[i], rotations[j]
            Pp = Gi @ P @ Gj.T
            ii = slice(2*i, 2*i+2); jj = slice(2*j, 2*j+2)
            transformed[ii, ii] += weight * I2
            transformed[jj, jj] += weight * (Pp.T @ Pp)
            transformed[ii, jj] += -weight * Pp
            transformed[jj, ii] += -weight * Pp.T
        Lp = transformed.tocsr().toarray()
        expected = (G @ sp.csr_matrix(L) @ G.T).toarray()
        gauge_err = _relative_matrix_error(Lp, expected)
        assert gauge_err < 2e-12, (spin, gauge_err)
        checks[f"spin{spin}_discrete_local_gauge_covariance"] = gauge_err

        # The actual heat semigroup must transform covariantly as well. Build
        # the locally gauge-transformed graph eigensystem and compare
        # H_{A'}(G u) against G H_A(u).
        Lp_sparse = sp.csr_matrix(Lp)
        ms64 = g["mass_sqrt64"].astype(np.float64)
        Dinv = sp.diags(1.0 / ms64)
        Ap = (Dinv @ Lp_sparse @ Dinv).toarray()
        ep, Vp = np.linalg.eigh(Ap)
        gp = dict(g)
        gp["laplacian"] = Lp_sparse
        gp["eig64"] = np.maximum(ep, 0.0)
        gp["V64"] = Vp
        gp["eig"] = gp["eig64"].astype(np.float32)
        gp["V"] = Vp.astype(np.float32)
        z0 = rng_g.normal(size=(2, 6, 8)).astype(np.float64)
        hz = heat_numpy(z0, 0.07, g, 0.04)
        zvec = np.stack([z0[0].reshape(-1), z0[1].reshape(-1)], axis=-1)
        zrot = np.einsum("nij,nj->ni", np.stack(rotations), zvec)
        zrot_field = np.stack([zrot[:, 0].reshape(6, 8), zrot[:, 1].reshape(6, 8)])
        hz_rotated_geom = heat_numpy(zrot_field, 0.07, gp, 0.04)
        hz_expected_vec = np.einsum(
            "nij,nj->ni", np.stack(rotations),
            np.stack([hz[0].reshape(-1), hz[1].reshape(-1)], axis=-1))
        hz_expected = np.stack([hz_expected_vec[:, 0].reshape(6, 8),
                                hz_expected_vec[:, 1].reshape(6, 8)])
        heat_gauge_err = _relative_matrix_error(hz_rotated_geom, hz_expected)
        assert heat_gauge_err < 2e-10, (spin, heat_gauge_err)
        checks[f"spin{spin}_discrete_heat_local_gauge_covariance"] = heat_gauge_err

    # PDE1 is monostable: zero is unstable and q=sqrt(mu/eta) is stable.
    mu, eta = 0.55, 2.2
    qeq = math.sqrt(mu / eta)
    radial_zero_slope = mu
    radial_equilibrium_slope = mu - 3.0 * eta * qeq * qeq
    assert radial_zero_slope > 0.0 and radial_equilibrium_slope < 0.0
    qsmall = np.array([[[0.05]], [[0.0]]], dtype=np.float64)
    qgrow = reaction_radial_exact(qsmall, 0.1, mu, eta)
    assert np.linalg.norm(qgrow) > np.linalg.norm(qsmall)
    qeq_state = np.array([[[qeq]], [[0.0]]], dtype=np.float64)
    qeq_next = reaction_radial_exact(qeq_state, 0.2, mu, eta)
    assert abs(float(np.linalg.norm(qeq_next[:, 0, 0]) - qeq)) < 1e-12
    checks["pde2_vector_fisher_monostable"] = dict(
        zero_state_radial_slope=radial_zero_slope,
        equilibrium_amplitude=qeq,
        equilibrium_radial_slope=radial_equilibrium_slope)

    # PDE1 exact reaction preserves Q direction and approaches |Q|=sqrt(mu/eta).
    q0 = np.array([[[0.2]], [[-0.1]]], dtype=np.float64)
    q1 = reaction_radial_exact(q0, 0.1, 0.7, 3.0)
    dir_err = abs(float(q0[0, 0, 0] * q1[1, 0, 0] - q0[1, 0, 0] * q1[0, 0, 0]))
    assert dir_err < 1e-12
    qeq = math.sqrt(0.7 / 3.0)
    qeq_state = np.array([[[qeq]], [[0.0]]], dtype=np.float64)
    qeq_next = reaction_radial_exact(qeq_state, 0.2, 0.7, 3.0)
    assert abs(float(np.linalg.norm(qeq_next[:, 0, 0]) - qeq)) < 1e-12
    checks["pde3_radial_reaction"] = "PASS"

    # Reference split-step convergence on tiny grids for both new PDEs.
    for cname in ("pde1_chart_base",):
        case = case_catalogue()[cname]
        g = build_geometry(7, 9, case.train_curvature, case.spin, True)
        s = make_initial(91, g, case.pde)
        c = integrate_saved_interval(s, g, case, 0.01, 2, 16)
        f = integrate_saved_interval(s, g, case, 0.01, 4, 32)
        e = metric_relative_l2(c, f, g["area_grid"])
        assert e < 2e-4 and np.isfinite(e), (cname, e)
        checks[f"{cname}_reference_refinement"] = e

    return checks


