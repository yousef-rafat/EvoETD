FULL_MODELS = (
    "Connection-ETD-Fibre",
    "Scalar-Laplacian-ETD-Fibre",
    "Connection-ETD-FNOResidual",
    "Scalar-Laplacian-ETD-FNOResidual",
    "FNO2D",
    "ConvGRU",
)
SENSITIVITY_MODELS = (
    "Connection-ETD-Fibre",
    "Scalar-Laplacian-ETD-Fibre",
)
# Keep both matched ETD residual families and both generic neural baselines
# in curvature/resolution transfer studies; dropping one would weaken the
# comparison precisely where geometry conditioning is being tested.
TRANSFER_MODELS = FULL_MODELS


def models_for_group(group: str) -> Tuple[str, ...]:
    if group == "full":
        return FULL_MODELS
    if group == "sensitivity":
        return SENSITIVITY_MODELS
    if group in ("curvature", "transfer"):
        return TRANSFER_MODELS
    raise ValueError(f"Unknown model group {group}.")


def _model_seed_offset(name: str) -> int:
    # Same initial weights for each matched connection/scalar pair.
    if name in ("Connection-ETD-Fibre", "Scalar-Laplacian-ETD-Fibre"):
        return 100
    if name in ("Connection-ETD-FNOResidual", "Scalar-Laplacian-ETD-FNOResidual"):
        return 200
    if name == "FNO2D":
        return 300
    if name == "ConvGRU":
        return 400
    raise KeyError(name)


def build_model(name: str, in_channels: int, hist: int, width: int,
                modes: int, seed: int) -> Tuple[nn.Module, str]:
    offset = _model_seed_offset(name)
    set_seed(int(seed + offset))
    if name == "Connection-ETD-Fibre":
        return FibreConnectionETDModel(hist=hist, width=width), "connection_fibre"
    if name == "Scalar-Laplacian-ETD-Fibre":
        return FibreConnectionETDModel(hist=hist, width=width), "scalar_fibre"
    if name == "Connection-ETD-FNOResidual":
        return ConnectionETDModel(in_channels, width=width, modes=modes), "connection_fno"
    if name == "Scalar-Laplacian-ETD-FNOResidual":
        return ConnectionETDModel(in_channels, width=width, modes=modes), "scalar_fno"
    if name == "FNO2D":
        return ForecastModel(in_channels, kind="fno", hist=hist, width=width, modes=modes), "direct_fno"
    if name == "ConvGRU":
        return ForecastModel(in_channels, kind="gru", hist=hist, width=width, modes=modes), "direct_gru"
    raise KeyError(name)


def geometry_for_kind(kind: str, connection_geom: Dict[str, Any],
                      scalar_geom: Dict[str, Any]) -> Optional[Dict[str, Any]]:
    if kind.startswith("connection_"):
        return connection_geom
    if kind.startswith("scalar_"):
        return scalar_geom
    return None


def geometry_tensors(geom: Optional[Dict[str, Any]], device: torch.device) -> Optional[Dict[str, torch.Tensor]]:
    if geom is None:
        return None
    return {key: torch.as_tensor(geom[key], device=device)
            for key in ("V", "eig", "mass_sqrt", "wet_idx")}


def predict(model: nn.Module, kind: str, x: torch.Tensor, last: torch.Tensor,
            dt: torch.Tensor, geom_t: Optional[Dict[str, torch.Tensor]],
            nu: float) -> torch.Tensor:
    if kind.startswith("connection_") or kind.startswith("scalar_"):
        if geom_t is None:
            raise RuntimeError("ETD model missing geometry tensors.")
        return model(x, last, dt, geom_t, float(nu))
    return last + model(x)


def train_model(model: nn.Module, kind: str, train_ds: Dataset, val_ds: Dataset,
                train_geom: Dict[str, Any], scalar_train_geom: Dict[str, Any],
                case: Case, args, seed: int, residual_bound: float,
                device: torch.device, label: str) -> Tuple[nn.Module, List[dict], float, float]:
    model.to(device)
    if hasattr(model, "set_residual_bound"):
        model.set_residual_bound(residual_bound)
    selected_geom = geometry_for_kind(kind, train_geom, scalar_train_geom)
    gt = geometry_tensors(selected_geom, device)
    area = torch.as_tensor(train_geom["area_grid"], device=device, dtype=torch.float32)
    area = area / area.sum()
    generator = torch.Generator()
    generator.manual_seed(int(seed + 9127))
    if getattr(args, "batch_sampling", "trajectory-balanced") == "trajectory-balanced":
        n_trajectories = len(train_ds.trajectory_indices)
        if int(args.batch_size) != n_trajectories:
            raise ValueError(
                "trajectory-balanced sampling requires --batch-size to equal "
                f"--train-trajectories ({n_trajectories}); otherwise it changes "
                "the number of optimizer updates per epoch.")
        batch_sampler = TrajectoryBalancedBatchSampler(
            train_ds.trajectory_indices, args.batch_size, seed=int(seed + 9127))
        tr_loader = DataLoader(train_ds, batch_sampler=batch_sampler, num_workers=0,
                               pin_memory=(device.type == "cuda"))
    else:
        tr_loader = DataLoader(train_ds, batch_size=args.batch_size, shuffle=True,
                               generator=generator, num_workers=0, drop_last=False,
                               pin_memory=(device.type == "cuda"))
    va_loader = DataLoader(val_ds, batch_size=args.batch_size, shuffle=False,
                           num_workers=0, pin_memory=(device.type == "cuda"))
    opt = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=args.weight_decay)
    scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(opt, mode="min", factor=0.5, patience=4)
    grad_clip_norm = float(getattr(args, "grad_clip_norm", 1.0))
    warmup_epochs = int(getattr(args, "warmup_epochs", 0))
    ema_decay = float(getattr(args, "ema_decay", 0.0))
    if (not math.isfinite(grad_clip_norm) or grad_clip_norm <= 0 or warmup_epochs < 0
            or not math.isfinite(ema_decay) or not (0.0 <= ema_decay < 1.0)):
        raise ValueError("Invalid gradient clipping, warmup, or EMA configuration.")
    ema_model = copy.deepcopy(model) if ema_decay > 0 else None
    best_val = float("inf"); best_state = None; bad_epochs = 0; history = []
    started = time.monotonic()

    for epoch in range(args.epochs):
        if warmup_epochs > 0 and epoch < warmup_epochs:
            warm_lr = args.lr * float(epoch + 1) / float(warmup_epochs)
            for group in opt.param_groups:
                group["lr"] = warm_lr
        model.train(); train_losses = []; grad_norms = []
        for x, last, target, dtime in tr_loader:
            x = x.to(device, non_blocking=True); last = last.to(device, non_blocking=True)
            target = target.to(device, non_blocking=True)
            dtime = dtime.to(device).view(-1, 1, 1, 1)
            opt.zero_grad(set_to_none=True)
            pred = predict(model, kind, x, last, dtime, gt, case.nu)
            if not torch.isfinite(pred).all():
                raise FloatingPointError(f"Non-finite training prediction: {label}, epoch={epoch+1}")
            loss = (((pred - target) ** 2) * area[None, None]).sum() / (2.0 * len(x))
            if not torch.isfinite(loss):
                raise FloatingPointError(f"Non-finite training loss: {label}, epoch={epoch+1}")
            loss.backward()
            grad_norm = torch.nn.utils.clip_grad_norm_(model.parameters(), grad_clip_norm, error_if_nonfinite=True)
            grad_norms.append(float(grad_norm.detach().cpu()))
            if not torch.isfinite(grad_norm):
                raise FloatingPointError(f"Non-finite gradient norm: {label}, epoch={epoch+1}")
            opt.step()
            if ema_model is not None:
                with torch.no_grad():
                    for p_ema, p_live in zip(ema_model.parameters(), model.parameters()):
                        p_ema.mul_(ema_decay).add_(p_live, alpha=(1.0 - ema_decay))
                    for b_ema, b_live in zip(ema_model.buffers(), model.buffers()):
                        b_ema.copy_(b_live)
            train_losses.append(float(loss.detach().cpu()))

        model.eval(); val_num = 0.0; val_den = 0.0
        with torch.no_grad():
            for x, last, target, dtime in va_loader:
                x = x.to(device, non_blocking=True); last = last.to(device, non_blocking=True)
                target = target.to(device, non_blocking=True)
                dtime = dtime.to(device).view(-1, 1, 1, 1)
                pred = predict(model, kind, x, last, dtime, gt, case.nu)
                if not torch.isfinite(pred).all():
                    raise FloatingPointError(f"Non-finite validation prediction: {label}, epoch={epoch+1}")
                val_num += float((((pred - target) ** 2) * area[None, None]).sum().cpu())
                val_den += 2.0 * len(x)
        val_loss = val_num / max(val_den, 1e-12)
        ema_val_loss = float("nan")
        candidate_model = model
        candidate_val = val_loss
        candidate_source = "raw"
        if ema_model is not None:
            ema_model.eval(); ema_num = 0.0; ema_den = 0.0
            with torch.no_grad():
                for x, last, target, dtime in va_loader:
                    x = x.to(device, non_blocking=True); last = last.to(device, non_blocking=True)
                    target = target.to(device, non_blocking=True)
                    dtime = dtime.to(device).view(-1, 1, 1, 1)
                    pred = predict(ema_model, kind, x, last, dtime, gt, case.nu)
                    if not torch.isfinite(pred).all():
                        raise FloatingPointError(f"Non-finite EMA validation prediction: {label}, epoch={epoch+1}")
                    ema_num += float((((pred - target) ** 2) * area[None, None]).sum().cpu())
                    ema_den += 2.0 * len(x)
            ema_val_loss = ema_num / max(ema_den, 1e-12)
            if ema_val_loss < candidate_val:
                candidate_val = ema_val_loss
                candidate_model = ema_model
                candidate_source = "ema"
        scheduler.step(candidate_val)
        history.append(dict(epoch=epoch + 1, train=float(np.mean(train_losses)), val=val_loss,
                            ema_val=ema_val_loss, selected_val=candidate_val,
                            selected_checkpoint=candidate_source,
                            learning_rate=float(opt.param_groups[0]["lr"]),
                            grad_norm_mean=float(np.mean(grad_norms)) if grad_norms else float("nan"),
                            grad_norm_max=float(np.max(grad_norms)) if grad_norms else float("nan"),
                            grad_clip_fraction=float(np.mean(np.asarray(grad_norms) > grad_clip_norm)) if grad_norms else float("nan")))
        if candidate_val < best_val:
            best_val = candidate_val
            best_state = {k: v.detach().cpu().clone() for k, v in candidate_model.state_dict().items()}
            bad_epochs = 0
        else:
            bad_epochs += 1
        elapsed = time.monotonic() - started
        eta = elapsed / (epoch + 1) * max(0, args.epochs - epoch - 1)
        print(f"[EXT-TRAIN][{label}] epoch {epoch+1}/{args.epochs} "
              f"train={np.mean(train_losses):.6g} val={val_loss:.6g} "
              f"elapsed={elapsed/60:.1f}m ETA~{eta/60:.1f}m", flush=True)
        if bad_epochs >= args.patience:
            break

    if best_state is None:
        raise RuntimeError(f"No finite checkpoint produced for {label}.")
    model.load_state_dict(best_state)
    return model, history, best_val, time.monotonic() - started


