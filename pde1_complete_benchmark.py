def evaluate_rollout(model: nn.Module, kind: str, test: np.ndarray,
                     test_geom: Dict[str, Any], test_scalar_geom: Dict[str, Any],
                     case: Case, scale: float, args, seed: int, model_name: str,
                     device: torch.device) -> Tuple[List[dict], float, Optional[dict]]:
    model.eval()
    selected_geom = geometry_for_kind(kind, test_geom, test_scalar_geom)
    gt = geometry_tensors(selected_geom, device)
    H, W = test_geom["mask"].shape
    valid = np.ones((args.history, H, W), dtype=np.float32)
    rows: List[dict] = []
    latencies: List[float] = []
    failure = None

    # Warm up kernels before collecting inference latency; exclude first-call
    # CUDA/context and FFT initialization overhead from the steady-state metric.
    warm_traj = test[0]
    warm_hist = np.stack([warm_traj[i] for i in range(args.train_steps - args.history + 1,
                                                      args.train_steps + 1)]) / scale
    warm_x = torch.from_numpy(make_features(warm_hist, valid, [1.0] * args.history, 1.0, test_geom)[None]).to(device)
    warm_last = torch.from_numpy(warm_hist[-1:]).to(device)
    warm_dt = torch.full((1, 1, 1, 1), float(args.dt), device=device, dtype=warm_last.dtype)
    with torch.no_grad():
        _ = predict(model, kind, warm_x, warm_last, warm_dt, gt, case.nu)
    if device.type == "cuda":
        torch.cuda.synchronize(device)

    for tid, traj in enumerate(test):
        state_hist = [traj[i].copy() for i in range(args.train_steps - args.history + 1,
                                                   args.train_steps + 1)]
        for horizon in range(1, args.steps - args.train_steps + 1):
            hstate = np.stack(state_hist) / scale
            features = make_features(hstate, valid, [1.0] * args.history, 1.0, test_geom)
            x = torch.from_numpy(features[None]).to(device)
            last = torch.from_numpy(hstate[-1][None].astype(np.float32)).to(device)
            dtime = torch.full((1, 1, 1, 1), float(args.dt), device=device, dtype=last.dtype)
            if device.type == "cuda":
                torch.cuda.synchronize(device)
            t0 = time.perf_counter()
            try:
                with torch.no_grad():
                    pred = predict(model, kind, x, last, dtime, gt, case.nu)[0].detach().cpu().numpy() * scale
            except Exception as exc:
                failure = dict(case=case.name, seed=seed, model=model_name, trajectory=tid,
                               horizon=horizon, reason=repr(exc), phase="rollout")
                break
            if device.type == "cuda":
                torch.cuda.synchronize(device)
            latencies.append((time.perf_counter() - t0) * 1000.0)
            if not np.isfinite(pred).all():
                failure = dict(case=case.name, seed=seed, model=model_name, trajectory=tid,
                               horizon=horizon, reason="non-finite prediction", phase="rollout")
                break
            truth = traj[args.train_steps + horizon]
            rel = metric_relative_l2(pred, truth, test_geom["area_grid"])
            rows.append(dict(case=case.name, pde=case.pde, seed=seed,
                             test_trajectory=tid, model=model_name, horizon=horizon,
                             elapsed_time=horizon * args.dt, rel_l2=rel,
                             train_curvature=case.train_curvature,
                             test_curvature=case.resolved_test_curvature,
                             nu=case.nu, mu=case.mu, eta=case.eta, alpha=case.alpha,
                             train_height=case.train_height, train_width=case.train_width,
                             test_height=H, test_width=W))
            state_hist = state_hist[1:] + [pred.astype(np.float32)]
        if failure is not None:
            break
    latency = float(np.mean(latencies)) if latencies else float("nan")
    return rows, latency, failure


