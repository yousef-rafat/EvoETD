def _cell_widths(x: np.ndarray) -> np.ndarray:
    x = np.asarray(x, dtype=np.float64)
    if x.ndim != 1 or len(x) < 2 or not np.isfinite(x).all() or np.any(np.diff(x) <= 0):
        raise ValueError("Grid coordinates must be finite, one-dimensional and strictly ascending.")
    edges = np.empty(len(x) + 1, dtype=np.float64)
    edges[1:-1] = 0.5 * (x[:-1] + x[1:])
    edges[0] = x[0] - 0.5 * (x[1] - x[0])
    edges[-1] = x[-1] + 0.5 * (x[-1] - x[-2])
    return np.diff(edges)


def _metric_factor(y: np.ndarray, curvature: float) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Return f, f', f'' for ds^2=dy^2+f(y)^2 dx^2 with Gaussian curvature K.

    The normalization f(0)=1 is deliberately shared across K, so changing
    curvature does not silently rescale the x-coordinate by 1/sqrt(abs(K)).
    Gaussian curvature is K=-f''/f.
    """
    y = np.asarray(y, dtype=np.float64)
    K = float(curvature)
    if K > 1e-12:
        q = math.sqrt(K)
        f = np.cos(q * y)
        fp = -q * np.sin(q * y)
        fpp = -K * f
    elif K < -1e-12:
        q = math.sqrt(-K)
        f = np.cosh(q * y)
        fp = q * np.sinh(q * y)
        fpp = (-K) * f
    else:
        f = np.ones_like(y)
        fp = np.zeros_like(y)
        fpp = np.zeros_like(y)
    if np.any(f <= 0) or not np.isfinite(f).all():
        raise ValueError("Metric chart reaches a singular/non-positive metric factor; reduce y_extent or |K|.")
    inferred = -fpp / f
    if not np.allclose(inferred, K, atol=1e-10, rtol=1e-10):
        raise AssertionError("Analytic metric does not have requested constant curvature.")
    return f, fp, fpp


def build_geometry(height: int, width: int, curvature: float, spin: int,
                   with_connection: bool, x_extent: float = 1.6,
                   y_extent: float = 1.2) -> Dict[str, Any]:
    """Finite-volume Bochner graph on a constant-curvature patch.

    Metric: ds^2 = dy^2 + f_K(y)^2 dx^2; K=-f''/f.
    The spin-s representation parallel-transports a two-component fibre value
    by the rotation angle s*f'(y)*dx along a horizontal edge. Vertical chart
    edges are parallel in this frame. Natural no-flux conditions are obtained
    by omitting edges that leave the rectangular patch.

    Graph energy: sum_(i,j) w_ij ||v_i - P_(j->i) v_j||^2.
    The matrix uses interleaved (component-1, component-2) ordering per vertex.
    """
    if height < 5 or width < 5:
        raise ValueError("Geometry requires at least a 5x5 grid.")
    if spin not in (1, 2):
        raise ValueError("Only spin-1 tangent vectors and spin-2 traceless Q tensors are supported.")
    key = (int(height), int(width), round(float(curvature), 12), int(spin), bool(with_connection))
    if key in _GEOMETRY_CACHE:
        return _GEOMETRY_CACHE[key]

    x = np.linspace(-x_extent / 2, x_extent / 2, width, dtype=np.float64)
    y = np.linspace(-y_extent / 2, y_extent / 2, height, dtype=np.float64)
    dx = np.diff(x); dy = np.diff(y)
    dxw = _cell_widths(x); dyw = _cell_widths(y)
    f, fp, fpp = _metric_factor(y, curvature)
    ngrid = height * width
    wet_idx = np.arange(ngrid, dtype=np.int64)  # no internal holes; patch boundary is natural Neumann
    n = ngrid
    dim = 2 * n
    Kmat = sp.lil_matrix((dim, dim), dtype=np.float64)
    I = np.eye(2, dtype=np.float64)
    edge_records: List[Tuple[int, int, np.ndarray, float]] = []

    def add_edge(g0: int, g1: int, P: np.ndarray, weight: float) -> None:
        i = int(g0); j = int(g1)
        ii = slice(2 * i, 2 * i + 2)
        jj = slice(2 * j, 2 * j + 2)
        Kmat[ii, ii] += weight * I
        Kmat[jj, jj] += weight * (P.T @ P)
        Kmat[ii, jj] += -weight * P
        Kmat[jj, ii] += -weight * P.T
        edge_records.append((i, j, P.copy(), float(weight)))

    # Horizontal edge conductance = dual y-length / primal x-length.
    for iy in range(height):
        for ix in range(width - 1):
            dl = dx[ix]
            w = dyw[iy] / (f[iy] * dl)
            angle = (spin * fp[iy] * dl) if with_connection else 0.0
            c, s = math.cos(angle), math.sin(angle)
            P = np.array([[c, -s], [s, c]], dtype=np.float64)
            add_edge(iy * width + ix, iy * width + ix + 1, P, w)

    # Vertical edge conductance = dual x-length / primal y-length.
    for iy in range(height - 1):
        dp = dy[iy]
        fmid = 0.5 * (f[iy] + f[iy + 1])
        for ix in range(width):
            w = fmid * dxw[ix] / dp
            add_edge(iy * width + ix, (iy + 1) * width + ix, I, w)

    Kmat = ((Kmat.tocsr() + Kmat.T.tocsr()) * 0.5).tocsr()
    area_grid = f[:, None] * dyw[:, None] * dxw[None, :]
    area = area_grid.reshape(-1)
    mass = np.repeat(area, 2)
    invsqrt = 1.0 / np.sqrt(mass)
    A = (sp.diags(invsqrt) @ Kmat @ sp.diags(invsqrt)).toarray()
    eig, V = np.linalg.eigh(A)
    min_eig = float(eig.min())
    if min_eig < -1e-8:
        raise RuntimeError(f"Bochner graph is not positive semidefinite: min eigenvalue {min_eig}")
    eig = np.maximum(eig, 0.0)
    orth = float(np.linalg.norm(V.T @ V - np.eye(dim), ord=2))
    if orth > 2e-7:
        raise RuntimeError(f"Eigenvector orthogonality failure: {orth}")

    # Constant-curvature chart connection has a nontrivial holonomy. Store the
    # actual chart coordinates as smooth, dimensionless input channels.
    X, Y = np.meshgrid(x, y)
    geom = dict(
        V=V.astype(np.float32), eig=eig.astype(np.float32),
        V64=V.copy(), eig64=eig.copy(),
        mass_sqrt=np.sqrt(mass).astype(np.float32),
        mass_sqrt64=np.sqrt(mass).copy(), wet_idx=wet_idx,
        area=area, area_grid=area_grid.astype(np.float32),
        laplacian=Kmat, edge_records=edge_records, curvature=float(curvature), spin=int(spin),
        connection=bool(with_connection), min_eigenvalue=min_eig,
        max_eigenvalue=float(eig.max()), orthogonality=orth,
        x=x, y=y, X=X, Y=Y, metric_factor=f, metric_factor_prime=fp,
        metric_factor_second=fpp, mask=np.ones((height, width), dtype=bool),
        height=height, width=width, x_extent=x_extent, y_extent=y_extent,
    )
    _GEOMETRY_CACHE[key] = geom
    return geom


def heat_numpy(state: np.ndarray, dt: float, geom: Dict[str, Any], nu: float) -> np.ndarray:
    """Independent float64 reference heat action in interleaved fibre ordering."""
    if dt < 0 or nu < 0:
        raise ValueError("Heat time and diffusion must be nonnegative.")
    H, W = state.shape[-2:]
    if state.shape != (2, H, W):
        raise ValueError(f"Expected state [2,H,W], got {state.shape}.")
    n = H * W
    # Graph eigenvectors use (u_1,v_1,u_2,v_2,...), not channel-block order.
    pair = np.stack([state[0].reshape(-1), state[1].reshape(-1)], axis=-1).reshape(2 * n)
    ms = geom.get("mass_sqrt64", geom["mass_sqrt"]).astype(np.float64)
    V = geom.get("V64", geom["V"]).astype(np.float64)
    eig = geom.get("eig64", geom["eig"]).astype(np.float64)
    coeff = V.T @ (ms * pair)
    out = (V @ (np.exp(-nu * dt * eig) * coeff)) / ms
    return out.reshape(n, 2).T.reshape(2, H, W)


def metric_relative_l2(pred: np.ndarray, truth: np.ndarray, area: np.ndarray) -> float:
    if not np.isfinite(pred).all() or not np.isfinite(truth).all():
        raise FloatingPointError("Non-finite field in metric_relative_l2.")
    w = np.asarray(area, dtype=np.float64)
    num = float(np.sum(w[None] * (pred.astype(np.float64) - truth.astype(np.float64)) ** 2))
    den = float(np.sum(w[None] * truth.astype(np.float64) ** 2))
    return math.sqrt(num / max(den, 1e-24))


# ----------------------------- initial conditions ----------------------------


def make_initial(seed: int, geom: Dict[str, Any], pde_name: str) -> np.ndarray:
    """Resolution-independent, smooth initial fields on the same chart."""
    rng = np.random.default_rng(seed)
    X, Y = geom["X"], geom["Y"]
    Xn = (X - X.min()) / max(float(X.max() - X.min()), 1e-12)
    Yn = (Y - Y.min()) / max(float(Y.max() - Y.min()), 1e-12)

    if pde_name == "cubic_quintic":
        # Bistable amplitudes: low background lies below the unstable root,
        # while two coherent patches are above it and evolve toward the high
        # stable amplitude. This generates fronts rather than trivial decay.
        centers = [
            (rng.uniform(0.22, 0.40), rng.uniform(0.34, 0.62), rng.uniform(0.075, 0.125)),
            (rng.uniform(0.60, 0.78), rng.uniform(0.36, 0.68), rng.uniform(0.080, 0.135)),
        ]
        amp = np.full_like(Xn, rng.uniform(0.08, 0.16), dtype=np.float64)
        for cx, cy, sig in centers:
            r2 = ((Xn - cx) ** 2 + rng.uniform(1.0, 1.6) * (Yn - cy) ** 2) / (2 * sig ** 2)
            amp += rng.uniform(1.10, 1.42) * np.exp(-r2)
        phase = (rng.uniform(0.20, 0.45) * np.sin(2 * np.pi * Xn + rng.uniform(0, 2*np.pi))
                 + rng.uniform(0.12, 0.30) * np.cos(2 * np.pi * Yn + rng.uniform(0, 2*np.pi))
                 + rng.uniform(0.06, 0.18) * np.sin(2 * np.pi * (Xn + Yn) + rng.uniform(0, 2*np.pi)))
        # Smooth random phase texture preserves the O(2)-symmetric reaction
        # while diversifying the fronts across independent initial conditions.
        phase += rng.uniform(0.01, 0.05) * np.sin(4 * np.pi * Xn + rng.uniform(0, 2 * np.pi))
        field = np.stack([amp * np.cos(phase), amp * np.sin(phase)])

    elif pde_name == "vector_fisher":
        # Spin-1 tangent-vector defects: a +1/-1 phase-winding pair. The
        # monostable radial reaction grows weak amplitudes toward sqrt(mu/eta),
        # while connection diffusion transports orientations across fibres.
        z1 = (Xn - rng.uniform(0.27, 0.39)) + 1j * (Yn - rng.uniform(0.38, 0.60))
        z2 = (Xn - rng.uniform(0.61, 0.74)) + 1j * (Yn - rng.uniform(0.40, 0.63))
        r1, r2 = np.abs(z1), np.abs(z2)
        phase = np.angle(z1) - np.angle(z2) + rng.uniform(0.0, 2.0 * np.pi)
        envelope = np.tanh(r1 / rng.uniform(0.05, 0.075)) * np.tanh(r2 / rng.uniform(0.05, 0.075))
        amp = rng.uniform(0.65, 0.85) * math.sqrt(0.55 / 2.2) * envelope
        amp *= 1.0 + 0.12 * np.cos(2 * np.pi * Xn + rng.uniform(0, 2*np.pi)) * np.sin(2 * np.pi * Yn + rng.uniform(0, 2*np.pi))
        field = np.stack([amp * np.cos(phase), amp * np.sin(phase)])

    elif pde_name == "nematic_q":
        # Intrinsic two-dimensional symmetric-traceless Q is represented by
        # q=( (Q11-Q22)/sqrt(2), sqrt(2) Q12 ), so ||q||_2=||Q||_F and q rotates
        # by 2*theta when the orthonormal tangent frame rotates by theta.
        z1 = (Xn - rng.uniform(0.27, 0.40)) + 1j * (Yn - rng.uniform(0.38, 0.60))
        z2 = (Xn - rng.uniform(0.60, 0.75)) + 1j * (Yn - rng.uniform(0.40, 0.64))
        r1, r2 = np.abs(z1), np.abs(z2)
        phase = np.angle(z1) - np.angle(z2) + rng.uniform(0.0, 2.0 * np.pi)  # +/-1/2 director defects
        defect_envelope = np.tanh(r1 / rng.uniform(0.045, 0.065)) * np.tanh(r2 / rng.uniform(0.045, 0.065))
        q0 = rng.uniform(0.62, 0.82) * math.sqrt(0.7 / 3.0)
        amp = q0 * defect_envelope
        # Smooth scalar modulation preserves the defect charges while creating
        # nontrivial relaxation beyond a stationary analytical texture.
        amp *= 1.0 + 0.10 * np.cos(2 * np.pi * Xn) * np.sin(2 * np.pi * Yn)
        field = np.stack([amp * np.cos(phase), amp * np.sin(phase)])
    else:
        raise ValueError(f"Unknown PDE family: {pde_name}")

    if not np.isfinite(field).all():
        raise FloatingPointError("Initial-condition generator produced non-finite values.")
    return field.astype(np.float64)


# ------------------------------- PDE references ------------------------------


def reaction_cubic_quintic_rk4(state: np.ndarray, dt: float, mu: float,
                                alpha: float, eta: float, substeps: int) -> np.ndarray:
    """RK4 for r_t=(mu+alpha*r^2-eta*r^4)r, applied pointwise."""
    if dt < 0 or substeps < 1 or eta <= 0:
        raise ValueError("Invalid cubic-quintic reaction integration settings.")
    z = np.asarray(state, dtype=np.float64).copy()
    h = dt / substeps
    def rhs(a):
        q = a[0] ** 2 + a[1] ** 2
        g = mu + alpha * q - eta * q * q
        return g[None] * a
    for _ in range(substeps):
        k1 = rhs(z)
        k2 = rhs(z + 0.5 * h * k1)
        k3 = rhs(z + 0.5 * h * k2)
        k4 = rhs(z + h * k3)
        z = z + (h / 6.0) * (k1 + 2 * k2 + 2 * k3 + k4)
        if not np.isfinite(z).all():
            raise FloatingPointError("Cubic-quintic RK4 reference reaction became non-finite.")
    return z


def reaction_radial_exact(state: np.ndarray, dt: float, mu: float, eta: float) -> np.ndarray:
    """Exact local flow for q_t=2(mu-eta*q)q, mu,eta>0."""
    if dt < 0 or mu <= 0 or eta <= 0:
        raise ValueError("Exact radial reaction requires dt>=0, mu>0, eta>0.")
    q = state[0] ** 2 + state[1] ** 2
    e = np.exp(2.0 * mu * dt)
    qn = (q * e) / (1.0 + (eta / mu) * q * (e - 1.0))
    factor = np.sqrt(np.maximum(qn, 0.0) / np.maximum(q, 1e-30))
    factor = np.where(q > 1e-24, factor, np.exp(mu * dt))
    out = state * factor[None]
    if not np.isfinite(out).all():
        raise FloatingPointError("Exact radial reaction produced non-finite values.")
    return out


def split_step(state: np.ndarray, dt: float, geom: Dict[str, Any], case: Case,
               reaction_substeps: int) -> np.ndarray:
    """Strang split: half heat, full local reaction, half heat."""
    z = heat_numpy(state, dt / 2.0, geom, case.nu)
    if case.pde == "cubic_quintic":
        z = reaction_cubic_quintic_rk4(z, dt, case.mu, case.alpha, case.eta,
                                       substeps=reaction_substeps)
    elif case.pde == "nematic_q":
        z = reaction_radial_exact(z, dt, case.mu, case.eta)
    elif case.pde == "vector_fisher":
        z = reaction_radial_exact(z, dt, case.mu, case.eta)
    else:
        raise ValueError(case.pde)
    z = heat_numpy(z, dt / 2.0, geom, case.nu)
    return z


def integrate_saved_interval(state: np.ndarray, geom: Dict[str, Any], case: Case,
                             dt: float, split_substeps: int,
                             reaction_substeps: int) -> np.ndarray:
    z = state.copy()
    for _ in range(split_substeps):
        z = split_step(z, dt / split_substeps, geom, case, reaction_substeps)
    return z


def generate_trajectories(ntraj: int, steps: int, geom: Dict[str, Any], case: Case,
                          seed: int, dt: float, split_substeps: int,
                          reaction_substeps: int, label: str) -> np.ndarray:
    all_tr = []
    started = time.monotonic()
    for tid in range(ntraj):
        state = make_initial(seed + 7919 * tid, geom, case.pde)
        seq = [state.astype(np.float32)]
        for step in range(steps):
            state = integrate_saved_interval(state, geom, case, dt, split_substeps,
                                             reaction_substeps)
            if not np.isfinite(state).all():
                raise FloatingPointError(f"Reference PDE became non-finite: {case.name} {label} trajectory={tid} step={step+1}")
            seq.append(state.astype(np.float32))
        all_tr.append(np.stack(seq))
        elapsed = time.monotonic() - started
        eta = elapsed / (tid + 1) * (ntraj - tid - 1)
        print(f"[EXT-DATA][{case.name}/{label}] trajectory {tid+1}/{ntraj} "
              f"elapsed={elapsed/60:.1f}m ETA~{eta/60:.1f}m", flush=True)
    return np.stack(all_tr).astype(np.float32)


