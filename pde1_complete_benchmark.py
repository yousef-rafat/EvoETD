def _sha256_file(path: Path, chunk_size: int = 1024 * 1024) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as f:
        while True:
            chunk = f.read(chunk_size)
            if not chunk:
                break
            digest.update(chunk)
    return digest.hexdigest()


def _validate_trajectory_split(name: str, array: np.ndarray, ntraj: int,
                               steps: int, height: int, width: int) -> None:
    expected = (int(ntraj), int(steps) + 1, 2, int(height), int(width))
    if not isinstance(array, np.ndarray) or array.shape != expected:
        actual = getattr(array, "shape", None)
        raise ValueError(f"{name} trajectories have shape {actual}; expected {expected}.")
    if array.dtype != np.float32:
        raise ValueError(f"{name} trajectories must be float32, got {array.dtype}.")
    if not np.isfinite(array).all():
        raise FloatingPointError(f"{name} trajectories contain NaN or infinity.")


def _metric_rows_complete(rows: Sequence[dict], case_name: str, seed: int,
                          model_name: str, args) -> bool:
    """Require every unique (test trajectory, horizon) metric and finite loss."""
    selected = [r for r in rows
                if str(r.get("case")) == case_name
                and str(r.get("model")) == model_name
                and _safe_int(r.get("seed"), -1) == int(seed)]
    expected = {(tid, h)
                for tid in range(int(args.test_trajectories))
                for h in range(1, int(args.steps) - int(args.train_steps) + 1)}
    observed = []
    try:
        for row in selected:
            key = (int(row["test_trajectory"]), int(row["horizon"]))
            value = float(row["rel_l2"])
            if not math.isfinite(value) or value < 0:
                return False
            observed.append(key)
    except (KeyError, TypeError, ValueError, OverflowError):
        return False
    return len(observed) == len(expected) and len(set(observed)) == len(expected) and set(observed) == expected


def _safe_int(value, default: int = -1) -> int:
    try:
        if pd.isna(value):
            return default
        return int(value)
    except (TypeError, ValueError, OverflowError):
        return default


def _resume_run_is_complete(rows: Sequence[dict], profiles: Sequence[dict],
                            manifests: Sequence[dict], case_name: str,
                            seed: int, model_name: str, args,
                            resume_signature: str) -> bool:
    matching = [m for m in manifests
                if str(m.get("case")) == case_name
                and _safe_int(m.get("seed")) == int(seed)
                and str(m.get("model")) == model_name]
    matching_profiles = [r for r in profiles
                         if str(r.get("case")) == case_name
                         and _safe_int(r.get("seed")) == int(seed)
                         and str(r.get("model")) == model_name]
    if len(matching) != 1 or len(matching_profiles) != 1:
        return False
    manifest = matching[0]
    profile = matching_profiles[0]
    if (str(manifest.get("runner_version", "")) != RUNNER_VERSION
            or str(manifest.get("status", "")) != "OK"
            or str(manifest.get("resume_signature", "")) != resume_signature
            or str(profile.get("status", "")) != "OK"):
        return False
    if not _metric_rows_complete(rows, case_name, seed, model_name, args):
        return False
    expected_rows = int(args.test_trajectories) * (int(args.steps) - int(args.train_steps))
    if _safe_int(manifest.get("metrics_rows"), -1) != expected_rows:
        return False
    checkpoint = Path(str(manifest.get("checkpoint", "")))
    if not checkpoint.is_file():
        return False
    try:
        if checkpoint.stat().st_size != _safe_int(manifest.get("checkpoint_size_bytes"), -1):
            return False
        if _sha256_file(checkpoint) != str(manifest.get("checkpoint_sha256", "")):
            return False
        best_val = float(manifest.get("best_validation_loss"))
        train_seconds = float(profile.get("train_seconds"))
        infer_ms = float(profile.get("inference_ms_per_step"))
        if not all(math.isfinite(x) and x >= 0 for x in (best_val, train_seconds, infer_ms)):
            return False
    except (OSError, TypeError, ValueError, OverflowError):
        return False
    return True


def summarize_case(case_dir: Path, bootstrap_samples: int, bootstrap_seed: int) -> None:
    metric_path = case_dir / "trajectory_metrics.csv"
    if not metric_path.exists():
        df = pd.DataFrame(columns=METRIC_COLUMNS)
    else:
        df = pd.read_csv(metric_path)
    if df.empty:
        _atomic_csv(pd.DataFrame(columns=SEED_LEVEL_COLUMNS), case_dir / "seed_level_metrics.csv")
        _atomic_csv(pd.DataFrame(columns=SUMMARY_COLUMNS), case_dir / "summary.csv")
        paired_bootstrap(df, case_dir / "paired_bootstrap.csv", bootstrap_samples, bootstrap_seed)
        return
    # First average trajectories within each training seed. Seeds, not the
    # seed x trajectory product, are the primary independent training units.
    seed_mean = (df.groupby(["case", "pde", "model", "seed", "horizon"], as_index=False)
                   .rel_l2.mean().rename(columns={"rel_l2": "seed_mean_rel_l2"}))
    summary = (seed_mean.groupby(["case", "pde", "model", "horizon"])
               .seed_mean_rel_l2.agg(["mean", "std", "count"]).reset_index()
               .rename(columns={"count": "n_seeds", "std": "seed_std"}))
    _atomic_csv(seed_mean, case_dir / "seed_level_metrics.csv")
    _atomic_csv(summary, case_dir / "summary.csv")
    df.attrs["bootstrap_horizons"] = _BOOTSTRAP_HORIZONS
    paired_bootstrap(df, case_dir / "paired_bootstrap.csv", bootstrap_samples, bootstrap_seed)


def paired_bootstrap(df: pd.DataFrame, path: Path, nboot: int = 5000,
                     seed: int = 20261106) -> None:
    """Paired two-way cluster bootstrap over training seeds and shared test IDs.

    Test trajectories are shared across models and training seeds. Resampling
    seeds and trajectory IDs independently preserves pairing and does not
    incorrectly count seed x trajectory cells as independent training runs.
    """
    if df.empty or not {"case", "horizon", "seed", "test_trajectory", "model", "rel_l2"}.issubset(df.columns):
        _atomic_csv(pd.DataFrame(columns=BOOTSTRAP_COLUMNS), path)
        return
    rng = np.random.default_rng(seed)
    comparisons = [
        ("Connection-ETD-Fibre", "Scalar-Laplacian-ETD-Fibre"),
        ("Connection-ETD-FNOResidual", "Scalar-Laplacian-ETD-FNOResidual"),
        ("Connection-ETD-Fibre", "FNO2D"),
        ("Connection-ETD-Fibre", "ConvGRU"),
    ]
    horizons = sorted(set(int(x) for x in df["horizon"].unique()))
    rows = []
    requested_horizons = set(int(x) for x in _BOOTSTRAP_HORIZONS)
    for (case_name, horizon), part in df.groupby(["case", "horizon"]):
        if int(horizon) not in requested_horizons:
            continue
        if part.duplicated(["seed", "test_trajectory", "model"]).any():
            raise ValueError(f"Duplicate paired observations in bootstrap group {case_name}, horizon={horizon}.")
        pivot = part.pivot(index=["seed", "test_trajectory"], columns="model",
                           values="rel_l2")
        seeds = np.array(sorted(part.seed.unique()))
        tids = np.array(sorted(part.test_trajectory.unique()))
        for candidate, comparator in comparisons:
            if candidate not in pivot.columns or comparator not in pivot.columns:
                continue
            mat = pivot[[candidate, comparator]].dropna()
            common_seeds = np.array(sorted(set(mat.index.get_level_values(0))))
            common_tids = np.array(sorted(set(mat.index.get_level_values(1))))
            expected_seeds = np.array(sorted(part.seed.unique()))
            expected_tids = np.array(sorted(part.test_trajectory.unique()))
            if len(expected_seeds) < 2 or len(expected_tids) < 2:
                continue
            # Require every configured seed and every shared held-out trajectory
            # for both models. Do not silently drop an entire failed test ID just
            # because both columns happen to be missing there.
            if not np.array_equal(common_seeds, expected_seeds):
                continue
            if not np.array_equal(common_tids, expected_tids):
                continue
            expected = {(int(s), int(t)) for s in expected_seeds for t in expected_tids}
            observed = set((int(s), int(t)) for s, t in mat.index)
            if expected != observed or len(mat) != len(expected):
                continue
            ns, nt = len(expected_seeds), len(expected_tids)
            mat = mat.reindex(pd.MultiIndex.from_product([expected_seeds, expected_tids],
                                                         names=mat.index.names))
            if mat.isna().any().any():
                continue
            vals = mat.to_numpy().reshape(len(common_seeds), len(common_tids), 2)
            obs_c = float(vals[:, :, 0].mean())
            obs_b = float(vals[:, :, 1].mean())
            obs_diff = obs_c - obs_b
            obs_improv = 1.0 - obs_c / max(obs_b, 1e-15)
            boot_diff = np.empty(nboot, dtype=np.float64)
            boot_improv = np.empty(nboot, dtype=np.float64)
            for b in range(nboot):
                si = rng.integers(0, ns, size=ns)
                ti = rng.integers(0, nt, size=nt)
                sample = vals[si[:, None], ti[None, :], :]
                mc = float(sample[:, :, 0].mean())
                mb = float(sample[:, :, 1].mean())
                boot_diff[b] = mc - mb
                boot_improv[b] = 1.0 - mc / max(mb, 1e-15)
            rows.append(dict(case=case_name, horizon=int(horizon), candidate=candidate,
                             comparator=comparator, candidate_mean=obs_c,
                             comparator_mean=obs_b, paired_difference=obs_diff,
                             relative_error_reduction=obs_improv,
                             difference_ci_low=float(np.quantile(boot_diff, 0.025)),
                             difference_ci_high=float(np.quantile(boot_diff, 0.975)),
                             reduction_ci_low=float(np.quantile(boot_improv, 0.025)),
                             reduction_ci_high=float(np.quantile(boot_improv, 0.975)),
                             n_seeds=ns, n_test_trajectories=nt, bootstrap_samples=nboot))
    _atomic_csv(pd.DataFrame(rows, columns=BOOTSTRAP_COLUMNS), path)


