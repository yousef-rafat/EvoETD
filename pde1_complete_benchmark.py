def heat_etd(last: torch.Tensor, residual: torch.Tensor, dt: torch.Tensor,
             geom: Dict[str, Any], nu: float | torch.Tensor) -> torch.Tensor:
    """Full-spectrum exponential Euler update in interleaved fibre order."""
    B, _, H, W = last.shape
    wet_idx = geom["wet_idx"]
    if not torch.is_tensor(wet_idx):
        wet_idx = torch.as_tensor(wet_idx, device=last.device, dtype=torch.long)
    V, eig, ms = geom["V"], geom["eig"], geom["mass_sqrt"]
    if not torch.is_tensor(V): V = torch.as_tensor(V, device=last.device)
    if not torch.is_tensor(eig): eig = torch.as_tensor(eig, device=last.device)
    if not torch.is_tensor(ms): ms = torch.as_tensor(ms, device=last.device)
    V = V.to(dtype=last.dtype); eig = eig.to(dtype=last.dtype); ms = ms.to(dtype=last.dtype)
    nwet = wet_idx.numel()
    xu = last[:, 0].reshape(B, -1).index_select(1, wet_idx)
    xv = last[:, 1].reshape(B, -1).index_select(1, wet_idx)
    ru = residual[:, 0].reshape(B, -1).index_select(1, wet_idx)
    rv = residual[:, 1].reshape(B, -1).index_select(1, wet_idx)
    x = torch.stack([xu, xv], dim=-1).reshape(B, 2 * nwet)
    r = torch.stack([ru, rv], dim=-1).reshape(B, 2 * nwet)
    xw = x * ms[None, :]; rw = r * ms[None, :]
    nu_t = nu if torch.is_tensor(nu) else torch.tensor(float(nu), device=last.device, dtype=last.dtype)
    nu_t = nu_t.to(device=last.device, dtype=last.dtype)
    if HEAT_ABLATION_MODE == "none":
        return last + dt.reshape(B, 1, 1, 1) * residual
    z = -nu_t * dt.reshape(B, 1) * eig.reshape(1, -1)
    E = torch.exp(z)
    large = torch.abs(z) > 1e-6
    safe_z = torch.where(large, z, torch.ones_like(z))
    phi1_large = torch.expm1(z) / safe_z
    phi1_small = 1.0 + 0.5 * z + z * z / 6.0
    phi1 = torch.where(large, phi1_large, phi1_small)
    cx = xw @ V; cr = rw @ V
    yw = (cx * E) @ V.T + dt.reshape(B, 1) * (cr * phi1) @ V.T
    y = (yw / ms[None, :]).reshape(B, nwet, 2)
    u = torch.zeros((B, H * W), device=last.device, dtype=last.dtype).scatter(
        1, wet_idx[None, :].expand(B, -1), y[:, :, 0])
    v = torch.zeros((B, H * W), device=last.device, dtype=last.dtype).scatter(
        1, wet_idx[None, :].expand(B, -1), y[:, :, 1])
    return torch.stack([u.reshape(B, H, W), v.reshape(B, H, W)], dim=1)


class SpectralConv2d(nn.Module):
    def __init__(self, in_c: int, out_c: int, modes1: int = 8, modes2: int = 8):
        super().__init__(); self.m1 = modes1; self.m2 = modes2
        scale = 1.0 / (in_c * out_c)
        self.w1 = nn.Parameter(scale * torch.randn(in_c, out_c, modes1, modes2, dtype=torch.cfloat))
        self.w2 = nn.Parameter(scale * torch.randn(in_c, out_c, modes1, modes2, dtype=torch.cfloat))

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        B, C, H, W = x.shape; xf = torch.fft.rfft2(x, norm="ortho")
        out = torch.zeros(B, self.w1.shape[1], H, W // 2 + 1, dtype=torch.cfloat, device=x.device)
        m1 = min(self.m1, H // 2); m2 = min(self.m2, W // 2 + 1)
        out[:, :, :m1, :m2] = torch.einsum("bixy,ioxy->boxy", xf[:, :, :m1, :m2], self.w1[:, :, :m1, :m2])
        out[:, :, -m1:, :m2] = torch.einsum("bixy,ioxy->boxy", xf[:, :, -m1:, :m2], self.w2[:, :, :m1, :m2])
        return torch.fft.irfft2(out, s=(H, W), norm="ortho")


class FNO2d(nn.Module):
    def __init__(self, in_c: int, width: int = 32, modes: int = 8, blocks: int = 4, pad: int = 6):
        super().__init__(); self.fc0 = nn.Conv2d(in_c, width, 1)
        self.spec = nn.ModuleList([SpectralConv2d(width, width, modes, modes) for _ in range(blocks)])
        self.point = nn.ModuleList([nn.Conv2d(width, width, 1) for _ in range(blocks)])
        self.fc1 = nn.Conv2d(width, width, 1); self.fc2 = nn.Conv2d(width, 2, 1); self.pad = pad

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        h, w = x.shape[-2:]; p = min(self.pad, h - 1, w - 1)
        if p: x = nn.functional.pad(x, (p, p, p, p), mode="reflect")
        z = self.fc0(x)
        for spectral, point in zip(self.spec, self.point):
            z = nn.functional.gelu(spectral(z) + point(z))
        y = self.fc2(nn.functional.gelu(self.fc1(z)))
        return y[..., p:p+h, p:p+w] if p else y


class ConvGRUCell(nn.Module):
    def __init__(self, in_c: int, hid: int):
        super().__init__(); self.hid = hid
        self.gates = nn.Conv2d(in_c + hid, 2 * hid, 3, padding=1)
        self.cand = nn.Conv2d(in_c + hid, hid, 3, padding=1)

    def forward(self, x: torch.Tensor, h: Optional[torch.Tensor]):
        if h is None:
            h = torch.zeros(x.shape[0], self.hid, *x.shape[-2:], device=x.device, dtype=x.dtype)
        z, r = torch.sigmoid(self.gates(torch.cat([x, h], 1))).chunk(2, 1)
        q = torch.tanh(self.cand(torch.cat([x, r * h], 1)))
        return (1 - z) * h + z * q


class ConvGRU2d(nn.Module):
    def __init__(self, hist: int, width: int = 32):
        super().__init__(); self.hist = hist
        # At each frame: (u,v), validity, its time gap, plus six static/next-dt maps.
        self.cell = ConvGRUCell(2 + 1 + 1 + 6, width)
        self.head = nn.Sequential(nn.Conv2d(width, width, 3, padding=1), nn.GELU(), nn.Conv2d(width, 2, 1))

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        B, C, H, W = x.shape; hcount = self.hist
        vel = x[:, :2*hcount].reshape(B, hcount, 2, H, W)
        valid = x[:, 2*hcount:3*hcount].reshape(B, hcount, 1, H, W)
        histdt = x[:, 3*hcount:4*hcount].reshape(B, hcount, 1, H, W)
        aux = x[:, 4*hcount:]
        state = None
        for k in range(hcount):
            state = self.cell(torch.cat([vel[:, k], valid[:, k], histdt[:, k], aux], 1), state)
        return self.head(state)


class ForecastModel(nn.Module):
    def __init__(self, in_c: int, kind: str = "fno", hist: int = 4, width: int = 32, modes: int = 8):
        super().__init__(); self.kind = kind
        self.net = FNO2d(in_c, width, modes) if kind == "fno" else ConvGRU2d(hist, width)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.net(x)


def bound_vector_residual(residual: torch.Tensor, limit: torch.Tensor | float) -> torch.Tensor:
    lim = limit if torch.is_tensor(limit) else torch.tensor(float(limit), device=residual.device, dtype=residual.dtype)
    lim = lim.to(device=residual.device, dtype=residual.dtype).clamp_min(1e-8)
    mag = torch.sqrt(residual[:, 0].square() + residual[:, 1].square() + 1e-12)
    factor = lim * torch.tanh(mag / lim) / mag.clamp_min(1e-12)
    return residual * factor[:, None]


class ConnectionETDModel(nn.Module):
    """ETD model with a generic raw-component FNO forcing network.

    This is intentionally a flexible, unconstrained FNO baseline: unlike
    FibreConnectionETDModel, its learned residual is NOT locally gauge
    equivariant. The connection heat action itself is gauge-covariant.
    """
    def __init__(self, in_c: int, width: int = 32, modes: int = 8, nu_init: float = 1e-4, learn_nu: bool = False):
        super().__init__(); self.net = FNO2d(in_c, width, modes)
        self.log_nu = nn.Parameter(torch.tensor(math.log(max(nu_init, 1e-12)), dtype=torch.float32), requires_grad=learn_nu)
        self.register_buffer("residual_bound", torch.tensor(1.0, dtype=torch.float32))

    def set_residual_bound(self, value: float):
        self.residual_bound.fill_(float(value))

    def forward(self, x, last, dt, geom, nu):
        residual = bound_vector_residual(self.net(x), self.residual_bound)
        nu_eff = torch.exp(torch.clamp(self.log_nu, -18.0, 5.0)) if self.log_nu.requires_grad else nu
        return heat_etd(last, residual, dt, geom, nu_eff)


class EquivariantFibreResidual(nn.Module):
    """Pointwise O(2)-equivariant reaction map for spin-1/spin-2 fibre values."""
    def __init__(self, hist: int, width: int = 64):
        super().__init__(); self.hist = hist
        n_dot = hist * (hist + 1) // 2
        # Pairwise dot products + log magnitudes + validity/time + 6 invariant maps.
        n_scalar = n_dot + hist + 2 * hist + 6
        self.net = nn.Sequential(nn.Conv2d(n_scalar, width, 1), nn.GELU(),
                                 nn.Conv2d(width, width, 1), nn.GELU(),
                                 nn.Conv2d(width, hist, 1))
        if FIBRE_FINAL_INIT_STD > 0.0:
            nn.init.normal_(self.net[-1].weight, mean=0.0, std=FIBRE_FINAL_INIT_STD)
        else:
            nn.init.zeros_(self.net[-1].weight)
        nn.init.zeros_(self.net[-1].bias)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        B, C, H, W = x.shape; h = self.hist
        if C != 4 * h + 6:
            raise ValueError(f"Expected {4*h+6} channels for gauge-invariant fibre input, got {C}.")
        vel = x[:, :2*h].reshape(B, h, 2, H, W)
        valid = x[:, 2*h:3*h]; histdt = x[:, 3*h:4*h]; aux = x[:, 4*h:]
        mag = torch.sqrt(vel[:, :, 0].square() + vel[:, :, 1].square() + 1e-12)
        safe_mag = mag.clamp_min(1.0)
        unit = vel / safe_mag.unsqueeze(2)
        inv = [(unit[:, i] * unit[:, j]).sum(dim=1, keepdim=True)
               for i in range(h) for j in range(i, h)]
        logmag = torch.log1p(mag.clamp_max(1e30))
        scalar = torch.cat(inv + [logmag, valid, histdt, aux], dim=1)
        alpha = torch.tanh(self.net(scalar)) / float(h)
        out = torch.zeros((B, 2, H, W), device=x.device, dtype=x.dtype)
        for i in range(h):
            out = out + alpha[:, i:i+1] * unit[:, i]
        return out


